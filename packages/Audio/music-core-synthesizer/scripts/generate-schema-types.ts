// packages/Audio/music-core-synthesizer/scripts/generate-schema-types.ts

import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";
import { fileURLToPath, pathToFileURL } from "node:url";

import openapiTS, { astToString } from "openapi-typescript";

const currentFilePath = fileURLToPath(import.meta.url);
const currentDirectory = path.dirname(currentFilePath);
const packageRoot = path.resolve(currentDirectory, "..");

const inputPath = path.resolve(packageRoot, "src", "state.yml");
const outputDirectory = path.resolve(packageRoot, "src", "generated");
const outputPath = path.resolve(outputDirectory, "schema-types.ts");

async function main(): Promise<void> {
  const ast = await openapiTS(pathToFileURL(inputPath), {
    alphabetize: true,
    enum: true,
    immutable: true,
    additionalProperties: false,
    cwd: pathToFileURL(packageRoot),
  });

  const generatedBody = astToString(ast);

  const fileContent = [
    "/* eslint-disable */",
    "// ------------------------------------------------------------------------------",
    "// <auto-generated>",
    `// Generated from: ${toPortablePath(inputPath)}`,
    "// Do not edit this file directly.",
    "// Regenerate with: pnpm generate:schema-types",
    "// ------------------------------------------------------------------------------",
    "",
    generatedBody.trimEnd(),
    "",
  ].join("\n");

  await mkdir(outputDirectory, { recursive: true });
  await writeFile(outputPath, fileContent, "utf8");

  process.stdout.write(
    [
      "Generated TypeScript DTOs successfully.",
      `Input:  ${toPortablePath(inputPath)}`,
      `Output: ${toPortablePath(outputPath)}`,
      "",
    ].join("\n"),
  );
}

function toPortablePath(value: string): string {
  return value.split(path.sep).join("/");
}

void main().catch((error: unknown) => {
  const message =
    error instanceof Error
      ? (error.stack ?? error.message)
      : String(error);

  process.stderr.write(`${message}\n`);
  process.exitCode = 1;
});
