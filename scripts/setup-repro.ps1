<#
.SYNOPSIS
  Setup the repository for local analysis tools and build the tools container.

.DESCRIPTION
  - Ensures .env exists (uses .env.template if present)
  - Runs `pnpm install` in the MonoRepro workspace
  - Builds the tools container used for scans
  - Optionally starts the tools services (SonarQube/Postgres/tools) via docker-compose

.PARAMETER StartTools
  If provided, starts the tools compose profile after building.

.EXAMPLE
  .\setup-repro.ps1 -StartTools
#>

param(
  [switch]$StartTools
)

Set-StrictMode -Version Latest

$scriptRoot = Split-Path -Parent $MyInvocation.MyCommand.Definition
$monoRoot = Resolve-Path "$scriptRoot\.."
$repoRoot = Resolve-Path "$scriptRoot\..\.."
$composeFile = Join-Path $repoRoot 'docker\tools\docker-compose.yml'
$envFile = Join-Path $repoRoot '.env'
$envTemplate = Join-Path $repoRoot '.env.template'

Write-Host "Repo root: $repoRoot"
Write-Host "Mono workspace: $monoRoot"
Write-Host "Compose file: $composeFile"

# Ensure .env exists
if (-not (Test-Path $envFile)) {
  if (Test-Path $envTemplate) {
    Copy-Item -Path $envTemplate -Destination $envFile -Force
    Write-Host "Created .env from .env.template"
  } else {
    Write-Host ".env not found; creating a minimal .env with defaults"
    @"
# Minimal .env generated by setup-repro.ps1
POSTGRES_IMAGE=postgres
POSTGRES_TAG=13
POSTGRES_PORT=5432
POSTGRES_INTERNAL_PORT=5432
SONARQUBE_IMAGE=sonarqube
SONARQUBE_TAG=9.9-community
SONARQUBE_PORT=9000
SONAR_DB_USER=sonar
SONAR_DB_PASS=sonar
SONAR_DB_NAME=sonar
SONAR_LOGIN=admin
SONAR_PASS=admin
"@ | Out-File -FilePath $envFile -Encoding UTF8
    Write-Host "Wrote minimal .env"
  }
} else {
  Write-Host ".env already present"
}

# Run pnpm install in MonoRepro
Write-Host "Running pnpm install in MonoRepro (this may take a while)"
if (Get-Command pnpm -ErrorAction SilentlyContinue) {
  $proc = Start-Process -FilePath pnpm -ArgumentList 'install' -WorkingDirectory $monoRoot -NoNewWindow -Wait -PassThru
  if ($proc.ExitCode -ne 0) { Write-Warning "pnpm install exited with code $($proc.ExitCode)" }
} else {
  Write-Warning "pnpm not found on PATH. Please install pnpm (npm install -g pnpm) and re-run this script."; exit 2
}

# Build tools container
if (-not (Test-Path $composeFile)) {
  Write-Error "docker-compose file not found at $composeFile"; exit 3
}

if (-not (Get-Command docker -ErrorAction SilentlyContinue)) {
  Write-Error "Docker executable not found. Please install Docker Desktop and ensure 'docker' is on PATH."; exit 4
}

Write-Host "Building tools container..."
$buildCmd = "docker compose -f `"$composeFile`" build tools"
Write-Host $buildCmd
$buildProc = Start-Process -FilePath docker -ArgumentList @('compose','-f',$composeFile,'build','tools') -NoNewWindow -Wait -PassThru
if ($buildProc.ExitCode -ne 0) { Write-Warning "docker compose build exited with code $($buildProc.ExitCode)" }

if ($StartTools) {
  Write-Host "Starting tools services (profile 'tools')..."
  $upProc = Start-Process -FilePath docker -ArgumentList @('compose','-f',$composeFile,'--profile','tools','up','-d') -NoNewWindow -Wait -PassThru
  if ($upProc.ExitCode -ne 0) { Write-Warning "docker compose up exited with code $($upProc.ExitCode)" }
  else { Write-Host "Tools started. SonarQube should be available at http://localhost:$((Get-Content $envFile | Select-String 'SONARQUBE_PORT' | ForEach-Object {($_ -split '=')[1].Trim()} ) )" }
} else {
  Write-Host "Tools not started. Run with -StartTools to launch SonarQube/Postgres/tools."
}

Write-Host "Setup complete. Next steps: run scans via MonoRepro/scripts/run-scans-in-docker.ps1 or enter the tools container."

exit 0
